#!/usr/bin/env bash
# Regenerate Formula/seridian.rb for a release of this repo.
# Usage: scripts/update-formula.sh <version-without-v> <dir-with-tarballs>
# Tarballs are named seridian-v<version>-<target>.tar.gz; any target that is
# missing is left out of the formula (e.g. Linux before CI builds it).
set -euo pipefail
VERSION="$1"; DIR="$2"
REPO="seridian-dev/homebrew-tap"
BASE="https://github.com/${REPO}/releases/download/v${VERSION}"

sha() { local f="$DIR/seridian-v${VERSION}-$1.tar.gz"; [ -f "$f" ] && shasum -a 256 "$f" | cut -d' ' -f1; }
block() { # <indent> <target>
  local s; s=$(sha "$2") || return 0
  printf '%surl "%s/seridian-v%s-%s.tar.gz"\n%ssha256 "%s"\n' "$1" "$BASE" "$VERSION" "$2" "$1" "$s"
}

MAC_ARM=$(block "      " aarch64-apple-darwin); MAC_X86=$(block "      " x86_64-apple-darwin)
LNX_ARM=$(block "      " aarch64-unknown-linux-gnu); LNX_X86=$(block "      " x86_64-unknown-linux-gnu)
[ -n "$MAC_ARM" ] || { echo "the aarch64-apple-darwin tarball is required" >&2; exit 1; }

{
cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/update-formula.sh — do not edit by hand.
class Seridian < Formula
  desc "Developer CLI for Seridian Auth (identity, OIDC clients, agent tooling)"
  homepage "https://auth.seridian.dev"
  version "${VERSION}"
  license "MIT"

  on_macos do
    on_arm do
${MAC_ARM}
    end
EOF
[ -n "$MAC_X86" ] && printf '    on_intel do\n%s\n    end\n' "$MAC_X86"
echo "  end"
if [ -n "$LNX_ARM" ] || [ -n "$LNX_X86" ]; then
  echo ""; echo "  on_linux do"
  [ -n "$LNX_ARM" ] && printf '    on_arm do\n%s\n    end\n' "$LNX_ARM"
  [ -n "$LNX_X86" ] && printf '    on_intel do\n%s\n    end\n' "$LNX_X86"
  echo "  end"
fi
cat <<EOF

  def install
    bin.install "seridian"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/seridian --version")
  end
end
EOF
} > "$(dirname "$0")/../Formula/seridian.rb"
echo "Formula/seridian.rb -> v${VERSION}"
